#!/usr/bin/env python3
"""
make_ca_header.py - turn a CA.PEM file into ca_builtin.h, the root certificates that
are built into the firmware so that it can write /netthing/CA.PEM to a card that has none.

    python tools/make_ca_header.py sdcard/netthing/CA.PEM ca_builtin.h

Run it again whenever sdcard/netthing/CA.PEM changes (see tools/make_ca_pem.py), then rebuild.

Author: Thomas Dzubin
"""
import sys


def main():
    if len(sys.argv) != 3:
        print("usage: make_ca_header.py CA.PEM ca_builtin.h")
        return 2
    data = open(sys.argv[1], "rb").read()
    if b"-----BEGIN CERTIFICATE-----" not in data:
        print("that does not look like a PEM file of certificates")
        return 1
    lines = data.split(b"\n")
    out = [
        "/*",
        " * ca_builtin.h - GENERATED by tools/make_ca_header.py from sdcard/netthing/CA.PEM; do not edit.",
        " * The root certificates built into the firmware: written to /netthing/CA.PEM on a card that has",
        " * none, when the user agrees. %d bytes." % len(data),
        " */",
        "#ifndef CA_BUILTIN_H",
        "#define CA_BUILTIN_H",
        "",
        "static const char ca_builtin_pem[] =",
    ]
    for i, line in enumerate(lines):
        if i == len(lines) - 1 and line == b"":
            break
        text = line.decode("ascii")
        if "\"" in text or "\\" in text or "?" in text:
            print("unexpected character in the PEM text")
            return 1
        out.append('    "%s\\n"' % text.rstrip("\r"))
    out[-1] += ";"
    out.append("")
    out.append("#define CA_BUILTIN_SIZE (sizeof ca_builtin_pem - 1)")
    out.append("")
    out.append("#endif /* CA_BUILTIN_H */")
    open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %s (%d bytes of PEM)" % (sys.argv[2], len(data)))
    return 0


sys.exit(main())
